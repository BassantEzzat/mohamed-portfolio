import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';

// ====== الإعدادات ======
const INPUT = 'D:/Projects/raw-images';
const OUT_FULL = 'public/images/stills/full';
const OUT_THUMB = 'public/images/stills/thumb';
const MANIFEST = 'src/app/data/images.generated.ts';

const FULL_SIZE = 2400; // أطول ضلع للصورة الكبيرة
const THUMB_SIZE = 900; // أطول ضلع للصورة الصغيرة
const FULL_QUALITY = 82;
const THUMB_QUALITY = 75;

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.tif', '.tiff']);
// =======================

const slugify = (name) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const mb = (bytes) => (bytes / 1024 / 1024).toFixed(1);

async function main() {
  await fs.mkdir(OUT_FULL, { recursive: true });
  await fs.mkdir(OUT_THUMB, { recursive: true });

  const entries = await fs.readdir(INPUT, { withFileTypes: true });

  const files = entries
    .filter((e) => e.isFile() && IMAGE_EXT.has(path.extname(e.name).toLowerCase()))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  const skipped = entries
    .filter((e) => !files.includes(e.name))
    .map((e) => e.name + (e.isDirectory() ? '  (folder)' : ''));

  console.log(`\nFound ${files.length} images.`);
  if (skipped.length) {
    console.log(`Skipped ${skipped.length} item(s):`);
    skipped.forEach((s) => console.log('   - ' + s));
  }
  console.log('');

  const used = new Set();
  const result = [];
  let totalBefore = 0;
  let totalAfter = 0;

  for (let i = 0; i < files.length; i++) {
    const file = files[i];
    const input = path.join(INPUT, file);
    const base = path.parse(file).name;

    let id = slugify(base) || `img-${i + 1}`;
    while (used.has(id)) id += '-2';
    used.add(id);

    const fullPath = path.join(OUT_FULL, `${id}.webp`);
    const thumbPath = path.join(OUT_THUMB, `${id}.webp`);

    try {
      const before = (await fs.stat(input)).size;

      const fullInfo = await sharp(input, { limitInputPixels: false })
        .rotate()
        .resize({ width: FULL_SIZE, height: FULL_SIZE, fit: 'inside', withoutEnlargement: true })
        .webp({ quality: FULL_QUALITY })
        .toFile(fullPath);

      await sharp(input, { limitInputPixels: false })
        .rotate()
        .resize({ width: THUMB_SIZE, height: THUMB_SIZE, fit: 'inside', withoutEnlargement: true })
        .webp({ quality: THUMB_QUALITY })
        .toFile(thumbPath);

      totalBefore += before;
      totalAfter += fullInfo.size;

      result.push({
        id,
        src: `images/stills/full/${id}.webp`,
        thumb: `images/stills/thumb/${id}.webp`,
        width: fullInfo.width,
        height: fullInfo.height,
      });

      console.log(
        `[${i + 1}/${files.length}] ${file.padEnd(14)} -> ${id}.webp  ` +
          `${mb(before)}MB -> ${(fullInfo.size / 1024).toFixed(0)}KB  (${fullInfo.width}x${fullInfo.height})`,
      );
    } catch (err) {
      console.log(`[${i + 1}/${files.length}] FAILED ${file}: ${err.message}`);
    }
  }

  const ts =
    `// Auto-generated by scripts/optimize-images.mjs — do not edit by hand\n\n` +
    `export interface StillImage {\n` +
    `  id: string;\n  src: string;\n  thumb: string;\n  width: number;\n  height: number;\n}\n\n` +
    `export const STILLS: StillImage[] = ${JSON.stringify(result, null, 2)};\n`;

  await fs.writeFile(MANIFEST, ts, 'utf8');

  console.log(`\nDone. ${result.length} images processed.`);
  console.log(`Before: ${mb(totalBefore)}MB  ->  After (full): ${mb(totalAfter)}MB`);
  console.log(`Manifest: ${MANIFEST}\n`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
